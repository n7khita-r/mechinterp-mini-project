#!/usr/bin/env python3
"""Majority-class baselines for the label tasks. No GPU needed.

`tense`, `negation` and `subject_gender` have 3, 2 and 2 possible answers. On a
small held-out set, a model that has learnt only the *output format* and then
always emits the most frequent label scores the majority-class rate -- which can
look like a strong result. In the 4B run `subject_gender/en` reached 0.80 even
though English verbs carry no subject-gender marking at all, which is only
explicable as that kind of collapse.

So an accuracy on these tasks is uninterpretable without the floor beside it.
This computes the floor on *exactly* the held-out items stage 05 scored (read
back from its scores.json), and flags any cell whose accuracy does not beat it.

    python scripts/majority_baseline.py --model configs/model/gemma3_4b_h200.yaml

Writes paper/tables/majority_baseline.tex and prints a summary.
"""

from __future__ import annotations

import json
import sys
from collections import Counter

from _common import REPO_ROOT, RESULTS, parser, setup  # noqa: E402

sys.path.insert(0, str(REPO_ROOT / "src"))

from fvcm import PART2_LABEL, conditions_for  # noqa: E402
from fvcm import data as D  # noqa: E402
from fvcm.cache import write_json  # noqa: E402

COND_NAME = {"en": "English", "te": "Telugu", "rom": "Romanized", "tg": "Tenglish"}


def main() -> int:
    p = parser("majority-class baselines for the label tasks")
    args = p.parse_args()
    mcfg, exp, chash, out, started = setup(args, "majority_baseline")

    scores_path = RESULTS / "05_intervene" / mcfg.name / "scores.json"
    interv_path = RESULTS / "05_intervene" / mcfg.name / "intervention.json"
    if not scores_path.exists():
        print(f"missing {scores_path}; run stage 05 first")
        return 1

    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    interv = {f"{r['task']}|{r['condition']}": r
              for r in json.loads(interv_path.read_text(encoding="utf-8"))}

    # Withheld from the report for the reason given in scripts/09_report.py.
    exclude = {"tense"}
    rows, suspect = [], []
    for task in PART2_LABEL:
        if task in exclude:
            continue
        for cond in conditions_for(task):
            key = f"{task}|{cond}"
            if key not in scores or key not in interv:
                continue

            # The exact items stage 05 reported on, by id.
            held_ids = [s["item_id"] for s in scores[key]["with_fv"]]
            gold = {i.id: i.out for i in D.load_items(task, cond, exp)}
            labels = [gold[i] for i in held_ids if i in gold]
            if not labels:
                continue

            counts = Counter(labels)
            n = len(labels)
            majority_label, majority_n = counts.most_common(1)[0]
            majority = majority_n / n
            acc = float(interv[key]["acc_with_fv"])
            zero = float(interv[key]["acc_zero_shot"])

            # Equality with the floor is the signature of collapse: the model
            # emits one label for everything and is right exactly as often as
            # that label occurs.
            collapsed = abs(acc - majority) < 1e-9
            beats = acc - majority
            rows.append({
                "task": task, "condition": cond, "n": n,
                "n_classes": len(counts),
                "majority_label": majority_label,
                "majority_acc": round(majority, 4),
                "acc_zero_shot": round(zero, 4),
                "acc_with_fv": round(acc, 4),
                "above_majority": round(beats, 4),
                "collapsed_to_majority": collapsed,
                "label_counts": dict(counts),
            })
            if collapsed or beats <= 0:
                suspect.append(key)

    write_json(out / "majority_baseline.json", rows)

    hdr = f"{'task':16s} {'cond':5s} {'n':>4s} {'major':>6s} {'+FV':>6s} {'above':>7s}"
    print(f"\n{hdr}\n{'-' * len(hdr)}")
    for r in rows:
        mark = "  <- at/below floor" if r["collapsed_to_majority"] or r["above_majority"] <= 0 else ""
        print(f"{r['task']:16s} {r['condition']:5s} {r['n']:4d} "
              f"{r['majority_acc']:6.2f} {r['acc_with_fv']:6.2f} "
              f"{r['above_majority']:+7.2f}{mark}")

    # LaTeX: accuracy is meaningless on these tasks without the floor beside it,
    # so the table puts them in adjacent columns rather than in an appendix.
    tex = [r"% generated by scripts/majority_baseline.py -- do not edit",
           r"\begin{tabular}{llrrrr}", r"\toprule",
           r"task & condition & $n$ & majority & +FV & $\Delta$ \\", r"\midrule"]
    last = None
    for r in rows:
        if last and r["task"] != last:
            tex.append(r"\midrule")
        last = r["task"]
        name = r["task"].replace("_", " ")
        delta = r["above_majority"]
        cell = f"{delta:+.2f}" if delta > 0 else rf"\textbf{{{delta:+.2f}}}"
        tex.append(f"{name} & {COND_NAME[r['condition']]} & {r['n']} & "
                   f"{r['majority_acc']:.2f} & {r['acc_with_fv']:.2f} & {cell} \\\\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    tex_path = REPO_ROOT / "paper" / "tables" / "majority_baseline.tex"
    tex_path.parent.mkdir(parents=True, exist_ok=True)
    tex_path.write_text("\n".join(tex) + "\n", encoding="utf-8")

    print(f"\nwrote {tex_path.relative_to(REPO_ROOT)}")
    if suspect:
        print(f"\n{len(suspect)} cell(s) at or below the majority floor: {suspect}")
        print("Report these as 'not above chance', not as accuracies. An accuracy")
        print("equal to the majority rate is the signature of a model that emits")
        print("one label for every item.")
    else:
        print("\nevery label-task cell beats its majority floor")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
