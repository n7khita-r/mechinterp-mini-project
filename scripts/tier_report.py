#!/usr/bin/env python3
"""Accuracy by complexity tier. No GPU needed; reads stage 01's per-item scores.

The headline run evaluates `core` only, so it cannot say whether harder
registers degrade. This aggregates the tier sweep (scripts/run_tiers.sh) into
one table: tier x condition, pooled over tasks.

Pooling over tasks is the only way these cells are large enough to mean
anything -- sanskritized has ~61 items spread over four tasks -- so the table
reports n alongside every accuracy and drops cells below a floor.

    python scripts/tier_report.py --model configs/model/gemma3_4b_h200.yaml \
        --exp configs/exp/tiers.yaml

Writes paper/tables/tier_accuracy.tex and presentation-ready numbers.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict

from _common import REPO_ROOT, RESULTS, parser, setup  # noqa: E402

sys.path.insert(0, str(REPO_ROOT / "src"))

from fvcm.cache import write_json  # noqa: E402

MIN_N = 8                      # below this a cell is noise, not a measurement
COND_ORDER = ["en", "te", "rom", "tg"]
COND_NAME = {"en": "English", "te": "Telugu", "rom": "Romanized", "tg": "Tenglish"}
TIER_ORDER = ["core", "complex", "sanskritized", "rare", "literary_en"]
TIER_NAME = {"core": "core", "complex": "complex", "sanskritized": "sanskritized",
             "rare": "rare", "literary_en": "rare English"}


def main() -> int:
    p = parser("accuracy by complexity tier")
    p.add_argument("--scores", default=None,
                   help="override path to the tier run's scores.json")
    args = p.parse_args()
    mcfg, exp, chash, out, started = setup(args, "tier_report")

    path = (REPO_ROOT / args.scores if args.scores
            else RESULTS / "01_tiers" / mcfg.name / "scores.json")
    if not path.exists():
        print(f"missing {path}\nrun: bash scripts/run_tiers.sh {args.model}")
        return 1

    scores = json.loads(path.read_text(encoding="utf-8"))
    agg: dict[tuple[str, str], list[int]] = defaultdict(list)
    for s in scores:
        agg[(s["tier"], s["condition"])].append(1 if s["rank"] == 0 else 0)

    rows = []
    for tier in TIER_ORDER:
        for cond in COND_ORDER:
            hits = agg.get((tier, cond))
            if not hits:
                continue
            rows.append({"tier": tier, "condition": cond, "n": len(hits),
                         "acc": round(sum(hits) / len(hits), 4),
                         "thin": len(hits) < MIN_N})
    if not rows:
        print("no scores found")
        return 1
    write_json(out / "tier_accuracy.json", rows)

    hdr = f"{'tier':14s} {'cond':5s} {'n':>5s} {'10-shot':>8s}"
    print(f"\n{hdr}\n{'-' * len(hdr)}")
    for r in rows:
        mark = "  (thin)" if r["thin"] else ""
        print(f"{r['tier']:14s} {r['condition']:5s} {r['n']:5d} {r['acc']:8.2f}{mark}")

    # Relative drop from core, per condition: the quantity the claim is about.
    core = {r["condition"]: r["acc"] for r in rows if r["tier"] == "core"}
    print(f"\n{'change from core':24s}" + "".join(f"{COND_NAME[c]:>12s}"
                                                  for c in COND_ORDER if c in core))
    for tier in TIER_ORDER[1:]:
        by = {r["condition"]: r for r in rows if r["tier"] == tier}
        if not by:
            continue
        cells = []
        for c in COND_ORDER:
            if c not in core:
                continue
            r = by.get(c)
            cells.append(f"{r['acc'] - core[c]:+12.2f}" if r else f"{'--':>12s}")
        print(f"{TIER_NAME[tier]:24s}" + "".join(cells))

    tex = [r"% generated by scripts/tier_report.py -- do not edit",
           r"\begin{tabular}{l" + "rr" * len([c for c in COND_ORDER if c in core]) + "}",
           r"\toprule"]
    heads = [c for c in COND_ORDER if c in core]
    tex.append("tier & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{COND_NAME[c]}}}"
                                      for c in heads) + r" \\")
    tex.append(" & " + " & ".join("acc & $n$" for _ in heads) + r" \\")
    tex.append(r"\midrule")
    for tier in TIER_ORDER:
        by = {r["condition"]: r for r in rows if r["tier"] == tier}
        if not by:
            continue
        cells = []
        for c in heads:
            r = by.get(c)
            if not r:
                cells.append("-- & --")
            else:
                # A thin cell is printed in grey so it cannot be read as evidence.
                acc = (rf"\textcolor{{black!45}}{{{r['acc']:.2f}}}" if r["thin"]
                       else f"{r['acc']:.2f}")
                cells.append(f"{acc} & {r['n']}")
        tex.append(f"{TIER_NAME[tier]} & " + " & ".join(cells) + r" \\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    # Model-suffixed: this table is per-model, and a shared filename means a
    # second model silently overwrites the first model's numbers.
    tex_path = REPO_ROOT / "paper" / "tables" / f"tier_accuracy_{mcfg.name}.tex"
    tex_path.parent.mkdir(parents=True, exist_ok=True)
    tex_path.write_text("\n".join(tex) + "\n", encoding="utf-8")
    print(f"\nwrote {tex_path.relative_to(REPO_ROOT)}")

    thin = [f"{r['tier']}/{r['condition']}(n={r['n']})" for r in rows if r["thin"]]
    if thin:
        print(f"\n{len(thin)} thin cell(s), greyed in the table: {', '.join(thin)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
