def baselines(rows: list[dict], path: Path) -> Path:
    """Per cell: 10-shot accuracy, zero-shot accuracy, items kept by the filter."""
    tasks = sorted({r["task"] for r in rows})
    conds = [c for c in CONDITION_ORDER if any(r["condition"] == c for r in rows)]
    by = {(r["task"], r["condition"]): r for r in rows}

    header = " & ".join(["task"] + [f"\\multicolumn{{2}}{{c}}{{{CONDITION_LABEL[c]}}}"
                                    for c in conds])
    sub = " & ".join([""] + ["10-shot & kept"] * len(conds))
    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{l" + "rr" * len(conds) + "}",
        "\\toprule",
        header + " \\\\",
        sub + " \\\\",
        "\\midrule",
    ]
    for t in tasks:
        cells = []
        for c in conds:
            r = by.get((t, c), {})
            cells += [_fmt(r.get("top1")), str(r.get("n_kept", NA))]
        out.append(" & ".join([_esc(t.replace("_", " "))] + cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)


def fv_strength(rows: list[dict], path: Path) -> Path:
    """Zero-shot accuracy with the function vector, per task and condition."""
    tasks = sorted({r["task"] for r in rows})
    conds = [c for c in CONDITION_ORDER if any(r["condition"] == c for r in rows)]
    by = {(r["task"], r["condition"]): r for r in rows}

    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{l" + "c" * len(conds) + "}",
        "\\toprule",
        " & ".join(["task"] + [CONDITION_LABEL[c] for c in conds]) + " \\\\",
        "\\midrule",
    ]
    for t in tasks:
        cells = []
        for c in conds:
            r = by.get((t, c), {})
            cells.append(_ci(r.get("acc_with_fv"), r.get("lo"), r.get("hi")))
        out.append(" & ".join([_esc(t.replace("_", " "))] + cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)


def paired_gaps(deltas: list[dict], path: Path) -> Path:
    """Paired condition differences with bootstrap intervals, on row-aligned items."""
    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{llrrrl}",
        "\\toprule",
        "task & comparison & $n$ & acc$_A$ & acc$_B$ & $\\Delta$ [95\\% CI] \\\\",
        "\\midrule",
    ]
    for d in deltas:
        excl = np.isfinite(d.get("lo", np.nan)) and (d["lo"] > 0 or d["hi"] < 0)
        delta = f"{_fmt(d.get('delta'))}\\,[{_fmt(d.get('lo'))},{_fmt(d.get('hi'))}]"
        if excl:
            delta = "\\textbf{" + delta + "}"
        out.append(" & ".join([
            _esc(d.get("task", "").replace("_", " ")),
            f"{d['a']}$-${d['b']}",
            str(d.get("n", NA)),
            _fmt(d.get("acc_a")),
            _fmt(d.get("acc_b")),
            delta,
        ]) + " \\\\")
    out += [
        "\\bottomrule",
        "\\end{tabular}",
    ]
    return _write(path, out)


def head_sets(sets: dict[str, list], path: Path) -> Path:
    """The top heads selected per condition, and the pairwise overlap."""
    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{ll}",
        "\\toprule",
        "condition & top heads (layer.head) \\\\",
        "\\midrule",
    ]
    for cond in list(CONDITION_ORDER) + ["pooled"]:
        if cond not in sets:
            continue
        heads = ", ".join(f"{l}.{h}" for l, h, _ in sets[cond])
        label = CONDITION_LABEL.get(cond, cond)
        out.append(f"{label} & \\texttt{{{heads}}} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)


def tier_degradation(rows: list[dict], path: Path) -> Path:
    """Accuracy by tier and condition."""
    tiers = [t for t in TIER_ORDER if any(r["tier"] == t for r in rows)]
    conds = [c for c in CONDITION_ORDER if any(r["condition"] == c for r in rows)]
    by = {(r["tier"], r["condition"]): r for r in rows}

    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{l" + "c" * len(conds) + "}",
        "\\toprule",
        " & ".join(["tier"] + [CONDITION_LABEL[c] for c in conds]) + " \\\\",
        "\\midrule",
    ]
    for t in tiers:
        cells = [_ci(by.get((t, c), {}).get("acc"), by.get((t, c), {}).get("lo"),
                     by.get((t, c), {}).get("hi")) for c in conds]
        out.append(" & ".join([TIER_LABEL[t]] + cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)


def transfer(sources: list[str], targets: list[str], acc, path: Path) -> Path:
    """Cross-condition transfer: rows are where the vector came from."""
    m = np.asarray(acc, dtype=float)
    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{l" + "c" * len(targets) + "}",
        "\\toprule",
        " & ".join(["FV from $\\downarrow$ / applied to $\\rightarrow$"]
                   + [CONDITION_LABEL[t] for t in targets]) + " \\\\",
        "\\midrule",
    ]
    for i, s in enumerate(sources):
        out.append(" & ".join([CONDITION_LABEL[s]]
                              + [_fmt(m[i, j]) for j in range(len(targets))]) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)


def token_lengths(rows: list[dict], path: Path) -> Path:
    """Mean prompt and answer token counts per condition: the tokenization diagnostic."""
    conds = [c for c in CONDITION_ORDER if any(r["condition"] == c for r in rows)]
    by: dict[str, list[dict]] = {}
    for r in rows:
        by.setdefault(r["condition"], []).append(r)

    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{lrr}",
        "\\toprule",
        "condition & mean prompt tokens & mean answer tokens \\\\",
        "\\midrule",
    ]
    for c in conds:
        rs = by[c]
        p = float(np.nanmean([r.get("mean_prompt_tokens", np.nan) for r in rs]))
        a = float(np.nanmean([r.get("mean_answer_tokens", np.nan) for r in rs]))
        out.append(f"{CONDITION_LABEL[c]} & {_fmt(p, 1)} & {_fmt(a, 2)} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)


def controls(rows: list[dict], path: Path) -> Path:
    """Function vector against each control, at the selected layer."""
    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "task & condition & FV & random vec. & unrelated FV & shuffled floor \\\\",
        "\\midrule",
    ]
    for r in rows:
        out.append(" & ".join([
            _esc(r.get("task", "").replace("_", " ")),
            CONDITION_LABEL.get(r.get("condition"), r.get("condition", "")),
            _fmt(r.get("acc_fv")), _fmt(r.get("acc_random")),
            _fmt(r.get("acc_unrelated")), _fmt(r.get("acc_shuffled")),
        ]) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)


def dataset_summary(rows: list[dict], path: Path) -> Path:
    """Item counts per task and tier, for the Data section."""
    out = [
        "% generated by scripts/09_report.py -- do not edit",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "task & " + " & ".join(TIER_LABEL[t] for t in TIER_ORDER) + " & total \\\\",
        "\\midrule",
    ]
    for r in rows:
        counts = [r.get(t, 0) for t in TIER_ORDER]
        out.append(" & ".join([_esc(r["task"].replace("_", " "))]
                              + [str(c) for c in counts]
                              + [str(sum(counts))]) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return _write(path, out)
