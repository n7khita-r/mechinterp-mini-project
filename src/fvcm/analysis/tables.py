"""LaTeX table emitters.

Written as `\\input`-able fragments with no float wrapper, so the paper controls
placement and captions.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from .style import CONDITION_LABEL, CONDITION_ORDER, TIER_LABEL, TIER_ORDER

NA = "--"


def _fmt(x, nd: int = 2) -> str:
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return NA
    return f"{x:.{nd}f}"


def _ci(acc, lo, hi, nd: int = 2) -> str:
    if acc is None or (isinstance(acc, float) and not np.isfinite(acc)):
        return NA
    if lo is None or not np.isfinite(lo):
        return _fmt(acc, nd)
    return f"{_fmt(acc, nd)}\\,\\tiny{{[{_fmt(lo, nd)},{_fmt(hi, nd)}]}}"


def _write(path: Path, lines: list[str]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _esc(s: str) -> str:
    return str(s).replace("_", "\\_")


